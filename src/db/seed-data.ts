export function buildCooperativeNames(n: number) {
  const names: string[] = [];
  for (let i = 0; i < n; i++) {
    names.push(PREFIXES[i % PREFIXES.length] + (i >= PREFIXES.length ? ` ${Math.floor(i / PREFIXES.length) + 1}` : ""));
  }
  return names;
}
